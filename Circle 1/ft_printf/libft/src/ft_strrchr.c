#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	char	*str;

	str = (char *)s;
	while (*str != '\0')
		str++;
	while (*str != (char)c)
	{
		if (str == s)
			return (NULL);
		str--;
	}
	return ((char *)str);
}
